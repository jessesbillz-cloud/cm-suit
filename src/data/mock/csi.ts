export async function library(): Promise<CsiLibrary> {
  await delay();
  const divisions = [
    ...DIVISIONS.map(([number, title]) => ({ number, title, reserved: false })),
    ...RESERVED.map((number) => ({ number, title: 'Reserved for Future Expansion', reserved: true })),
  ].sort((a, b) => a.number.localeCompare(b.number));
  const sections = SECTIONS.map(([number, title]) => ({
    number,
    division: number.slice(0, 2),
    level: number.endsWith(' 00') ? 2 : 3,
    title,
  }));
  return { divisions, sections };
}
